import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(
  root,
  'src/copilotComponents/shared/mockData/embeddedImages.ts'
);

const sources = [
  { key: 'meganBowen', path: 'assets/faces/Megan-Bowen.jpeg', mime: 'image/jpeg' },
  { key: 'diegoSiciliani', path: 'assets/faces/Diego-Siciliani.jpeg', mime: 'image/jpeg' },
  { key: 'pattiFernandez', path: 'assets/faces/Patti-Fernandez.jpeg', mime: 'image/jpeg' },
  { key: 'leeGu', path: 'assets/faces/Lee-Gu.jpeg', mime: 'image/jpeg' },
  { key: 'johannaLorenz', path: 'assets/faces/Johanna-Lorenz.jpeg', mime: 'image/jpeg' },
  { key: 'nestorWilke', path: 'assets/faces/Nestor-Wilke.jpeg', mime: 'image/jpeg' },
  { key: 'pradeepGupta', path: 'assets/faces/Pradeep-Gupta.jpeg', mime: 'image/jpeg' },
  { key: 'employeeMoments', path: 'assets/images/zava-five-year-celebration.jpg', mime: 'image/jpeg' },
  { key: 'learningFocus', path: 'assets/images/zava-learning-focus.svg', mime: 'image/svg+xml' },
  { key: 'profilePlaceholder', path: 'assets/images/zava-profile-placeholder.svg', mime: 'image/svg+xml' }
];

const entries = sources.map((source) => {
  const bytes = readFileSync(resolve(root, source.path));
  return `  ${source.key}: 'data:${source.mime};base64,${bytes.toString('base64')}'`;
});

const generated = `// AUTO-GENERATED by scripts/generate-embedded-images.mjs. Do not edit by hand.\n` +
  `// All photos and graphics are embedded as data URIs for a fully offline runtime.\n\n` +
  `export const embeddedImages: { [key: string]: string } = {\n${entries.join(',\n')}\n};\n`;

if (process.argv.indexOf('--check') !== -1) {
  if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== generated) {
    console.error('Embedded image data is stale. Run npm run generate:mock-media.');
    process.exit(1);
  }
  console.log('Embedded image data is current.');
} else {
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, generated, 'utf8');
  console.log(`Generated ${sources.length} embedded images at ${outputPath}.`);
}