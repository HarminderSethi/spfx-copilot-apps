import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const sourceDirectory = path.join(root, 'assets', 'faces');
const outputFile = path.join(root, 'src', 'copilotComponents', 'shared', 'mockData', 'embeddedFaces.ts');
const check = process.argv.includes('--check');

const files = fs.readdirSync(sourceDirectory)
  .filter((file) => file.toLowerCase().endsWith('.jpeg'))
  .sort((left, right) => left.localeCompare(right));

if (files.length !== 11) {
  throw new Error(`Expected 11 bundled face images, found ${files.length}.`);
}

const entries = files.map((file) => {
  const key = path.basename(file, path.extname(file));
  const encoded = fs.readFileSync(path.join(sourceDirectory, file)).toString('base64');
  return `  '${key}': 'data:image/jpeg;base64,${encoded}'`;
});

const output = `// Generated by scripts/generate-embedded-faces.mjs. Do not edit manually.\nexport const EMBEDDED_FACES: Readonly<Record<string, string>> = {\n${entries.join(',\n')}\n};\n`;

if (check) {
  if (!fs.existsSync(outputFile) || fs.readFileSync(outputFile, 'utf8') !== output) {
    throw new Error('Embedded face registry is stale. Run npm run generate:mock-media.');
  }
  console.log(`Verified ${files.length} embedded face images.`);
} else {
  fs.mkdirSync(path.dirname(outputFile), { recursive: true });
  fs.writeFileSync(outputFile, output);
  console.log(`Generated ${files.length} embedded face images.`);
}
